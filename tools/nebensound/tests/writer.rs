/// A repository whose component `thing` selects the writer `cargo`, with
/// these files below it.
fn thing(files: &[(&str, &str)]) -> Git {
    let git = Git::new();
    let mut all = vec![(
        ".nebensound/repo.toml",
        "[repo]\npipeline = \"none\"\n\n[component.thing]\npath = \"thing\"\npipeline = { \
         version = [\"cargo\"] }\n",
    )];
    all.extend_from_slice(files);
    git.write(&all);
    git.commit("feat: start");
    git
}

