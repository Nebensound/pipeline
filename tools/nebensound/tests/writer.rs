#[test]
fn the_versions_come_from_a_plan_where_there_is_no_history() {
    let git = Git::new();
    git.write(&two_packages());
    git.commit("feat: start");
    let (plan, code) = call(&["nebensound", "-C", git.root(), "plan"]);
    assert_eq!(code, 0, "{plan}");
    let parsed: serde_json::Value = serde_json::from_str(&plan).expect("valid JSON");
    assert_eq!(parsed["versions"][0]["writers"], serde_json::json!([]));
    assert_eq!(
        parsed["versions"][1]["writers"],
        serde_json::json!(["cargo"])
    );
    let handed = tempfile::tempdir().expect("a folder for the plan");
    let file = handed.path().join("plan.json");
    fs::write(&file, &plan).expect("the plan is written");
    // A checkout without a single commit, as far from a history as it gets.
    let bare = repository(&two_packages());
    let root = bare.path().to_str().expect("a path in UTF-8");

    let (text, code) = call(&[
        "nebensound",
        "-C",
        root,
        "write-versions",
        "--plan",
        file.to_str().expect("a path in UTF-8"),
    ]);

    assert_eq!(code, 0, "{text}");
    assert!(text.contains("component app: the package app"), "{text}");
    cargo(bare.path(), &["build", "--locked"]);
    assert_eq!(reported(bare.path(), "lib"), "0.0.1");
}

#[test]
fn a_plan_that_does_not_read_is_refused() {
    let dir = repository(&two_packages());
    let root = dir.path().to_str().expect("a path in UTF-8");
    let handed = tempfile::tempdir().expect("a folder for the plan");
    let missing = handed.path().join("missing.json");
    let broken = handed.path().join("broken.json");
    fs::write(&broken, "{\"versions\": [{\"path\": \"../out\"}]}").expect("written");

    for file in [missing, broken] {
        let file = file.to_str().expect("a path in UTF-8");
        let (text, code) = call(&["nebensound", "-C", root, "write-versions", "--plan", file]);

        assert_eq!(code, 1, "{text}");
        assert!(
            text.starts_with(&format!("the plan {file} does not read: ")),
            "{text}"
        );
    }
    assert_eq!(read(dir.path(), "crates/lib/Cargo.toml"), LIB);
}

