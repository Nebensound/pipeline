#[test]
fn the_workspace_is_found_the_way_cargo_finds_it() {
    let git = Git::new();
    git.write(&[
        (
            ".nebensound/repo.toml",
            r#"[repo]
pipeline = { version = ["cargo"], check = ["rust"], dependabot = ["cargo"] }

[component.own]
path     = "crates/own"
pipeline = { version = ["cargo"], dependabot = ["cargo"] }

[component.far]
path     = "far/pkg"
pipeline = { version = ["cargo"] }
"#,
        ),
        // The root is a package and the workspace at once.
        (
            "Cargo.toml",
            "[package]\nname = \"root\"\nedition = \"2024\"\n\n[workspace]\nmembers = \
             [\"far/pkg\"]\nexclude = [\"crates/own\"]\n",
        ),
        (
            "Cargo.lock",
            "version = 4\n\n[[package]]\nname = \"far\"\nversion = \"0.0.0\"\n\n[[package]]\nname \
             = \"root\"\nversion = \"0.0.0\"\n",
        ),
        ("src/lib.rs", "//! The root.\n"),
        // Excluded from the workspace above it, so a workspace of its own.
        (
            "crates/own/Cargo.toml",
            "[package]\nname = \"own\"\nedition = \"2024\"\n",
        ),
        (
            "crates/own/Cargo.lock",
            "version = 4\n\n[[package]]\nname = \"own\"\nversion = \"0.0.0\"\n",
        ),
        ("crates/own/src/lib.rs", "//! Its own.\n"),
        // Names its workspace itself.
        (
            "far/pkg/Cargo.toml",
            "[package]\nname = \"far\"\nedition = \"2024\"\nworkspace = \"../..\"\n",
        ),
        ("far/pkg/src/lib.rs", "//! Far.\n"),
    ]);
    git.commit("feat: start");

    let (text, code) = call(&["nebensound", "-C", git.root(), "write-versions"]);

    assert_eq!(code, 0, "{text}");
    assert!(
        text.contains("the repository: the package root at . gets 0.0.1 (workspace root: .)."),
        "{text}"
    );
    assert!(text.contains("(workspace root: crates/own)"), "{text}");
    assert!(
        text.contains("component far: the package far at far/pkg gets 0.0.1 (workspace root: .)."),
        "{text}"
    );
    assert_eq!(
        read(git.path(), "Cargo.lock"),
        "version = 4\n\n[[package]]\nname = \"far\"\nversion = \"0.0.1\"\n\n[[package]]\nname = \
         \"root\"\nversion = \"0.0.1\"\n"
    );
    assert_eq!(
        read(git.path(), "crates/own/Cargo.lock"),
        "version = 4\n\n[[package]]\nname = \"own\"\nversion = \"0.0.1\"\n"
    );
    cargo(git.path(), &["build", "--locked", "--workspace"]);
    cargo(&git.path().join("crates/own"), &["build", "--locked"]);
}

