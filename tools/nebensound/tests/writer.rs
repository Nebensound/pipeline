/// A workspace of two packages, `app` depending on `lib` by path, each a unit
/// of its own with the writer `cargo`.
const DECLARATION: &str = r#"[repo]
pipeline = { check = ["rust"], dependabot = ["cargo"] }

[component.crates]
path       = "crates"
versioning = "child-folders"
pipeline   = { version = ["cargo"] }
"#;

const WORKSPACE: &str = "[workspace]\nmembers  = [\"crates/*\"]\nresolver = \"3\"\n";

/// What Cargo writes for [`WORKSPACE`], before any version is written.
const LOCKFILE: &str = "# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = \"app\"
version = \"0.0.0\"
dependencies = [
 \"lib\",
]

[[package]]
name = \"lib\"
version = \"0.0.0\"
";

const LIB: &str = "[package]\nname    = \"lib\"\nedition = \"2024\" # the edition\n";

const APP: &str = "[package]
name    = \"app\"
edition = \"2024\"

[dependencies]
lib = { path = \"../lib\" } # by path

[dev-dependencies.lib]
path = \"../lib\"
";

fn two_packages() -> Vec<(&'static str, &'static str)> {
    vec![
        (".nebensound/repo.toml", DECLARATION),
        ("Cargo.toml", WORKSPACE),
        ("Cargo.lock", LOCKFILE),
        ("crates/lib/Cargo.toml", LIB),
        (
            "crates/lib/src/lib.rs",
            "//! A library.\n\n/// One.\n#[must_use]\npub fn one() -> u8 {\n    1\n}\n",
        ),
        ("crates/app/Cargo.toml", APP),
        (
            "crates/app/src/main.rs",
            "//! An app.\n\nfn main() {\n    println!(\"{}\", lib::one());\n}\n",
        ),
    ]
}

/// A file of the fixture as it stands.
fn read(root: &Path, path: &str) -> String {
    fs::read_to_string(root.join(path)).expect("a file in the fixture")
}

/// Cargo in the fixture, offline and without what a coverage run sets for
/// its own build: the fixture is built plainly, into a folder of its own.
fn cargo(root: &Path, args: &[&str]) -> String {
    let target = tempfile::tempdir().expect("a target folder");
    cargo_into(root, target.path(), args)
}

/// The same, into a target folder the caller keeps.
fn cargo_into(root: &Path, target: &Path, args: &[&str]) -> String {
    let output = Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
        .args(args)
        .arg("--offline")
        .current_dir(root)
        .env("CARGO_TARGET_DIR", target)
        .env_remove("RUSTFLAGS")
        .env_remove("CARGO_ENCODED_RUSTFLAGS")
        .env_remove("RUSTDOCFLAGS")
        .env_remove("CARGO_ENCODED_RUSTDOCFLAGS")
        .env_remove("RUSTC_WRAPPER")
        .env_remove("RUSTC_WORKSPACE_WRAPPER")
        .env_remove("LLVM_PROFILE_FILE")
        .env_remove("CARGO_LLVM_COV")
        .env_remove("CARGO_LLVM_COV_TARGET_DIR")
        .env_remove("CARGO_BUILD_TARGET_DIR")
        .output()
        .expect("cargo runs");
    assert!(
        output.status.success(),
        "cargo {args:?}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).expect("cargo answers in UTF-8")
}

/// The version `cargo metadata` reports for a package of the fixture.
fn reported(root: &Path, name: &str) -> String {
    let metadata: serde_json::Value = serde_json::from_str(&cargo(
        root,
        &["metadata", "--format-version", "1", "--no-deps", "--locked"],
    ))
    .expect("cargo metadata prints JSON");
    metadata["packages"]
        .as_array()
        .expect("a list of packages")
        .iter()
        .find(|package| package["name"] == name)
        .and_then(|package| package["version"].as_str())
        .expect("the package is in the workspace")
        .to_owned()
}

#[test]
fn cargo_builds_locked_with_the_version_of_every_unit() {
    let git = Git::new();
    git.write(&two_packages());
    git.commit("feat: start");

    let (text, code) = call(&["nebensound", "-C", git.root(), "write-versions"]);

    assert_eq!(code, 0, "{text}");
    assert!(
        text.contains("component lib: the package lib at crates/lib gets 0.0.1"),
        "{text}"
    );
    assert!(text.contains("Wrote Cargo.lock."), "{text}");
    cargo(git.path(), &["build", "--locked"]);
    assert_eq!(reported(git.path(), "lib"), "0.0.1");
    assert_eq!(reported(git.path(), "app"), "0.0.1");
}

