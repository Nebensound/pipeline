//! The result as text: what the output says and where it comes from.

#![allow(clippy::expect_used, clippy::unwrap_used, clippy::panic)]

mod support;

use nebensound_repo::path::RelativePath;
use nebensound_repo::report;
use support::{analysis, central};

const WORKSPACE: &str = "\
[repo]
pipeline = \"rust-library\"

[component.docs]
path       = \"doc\"
pipeline   = \"typst-document\"
versioning = \"child-files\"
";

const WORKSPACE_FILES: &[&str] = &[
    "README.md",
    "LICENSE",
    "Cargo.toml",
    "Cargo.lock",
    ".nebensound/repo.toml",
    "src/lib.rs",
    "doc/a.typ",
    "doc/b.typ",
];

const MIXED: &str = "[repo]\npipeline = \"none\"\n";
const MIXED_FILES: &[&str] = &[
    "README.md",
    "LICENSE",
    "logo.png",
    "notes.xyz",
    "src/main.rs",
];

fn path(value: &str) -> RelativePath {
    RelativePath::new(value).expect("a path in the fixture")
}

#[test]
fn the_configuration_says_where_every_value_came_from() {
    let analysis = analysis(WORKSPACE, WORKSPACE_FILES);
    let text = report::configuration(&analysis, &central());

    assert!(text.contains("Base checks"), "{text}");
    assert!(text.contains("preset rust-library"), "{text}");
    assert!(text.contains("cargo-package"), "{text}");
    assert!(text.contains("private-registry"), "{text}");
    assert!(text.contains("history (versioning = "), "{text}");

    // The generated units say who generated them and that they declare nothing
    // of their own.
    assert!(text.contains("generated by component docs"), "{text}");
    assert!(text.contains("inherited"), "{text}");

    // The generating unit carries no version itself.
    assert!(
        text.contains("none (versioning = \"child-files\")"),
        "{text}"
    );
    assert!(analysis.findings().is_empty(), "{:?}", analysis.findings());
}

#[test]
fn the_configuration_names_every_origin() {
    let analysis = analysis(
        "\
[repo]
pipeline = { check = [\"rust\"] }

[repo.component]
pipeline = \"none\"

[component.a]
path = \"a\"

[component.b]
path          = \"b\"
pipeline.repo = true
",
        &["README.md", "a/x.rs", "b/y.rs"],
    );
    let text = report::configuration(&analysis, &central());

    assert!(text.contains("written out"), "{text}");
    assert!(text.contains("nothing declared"), "{text}");
    assert!(text.contains("the default in [repo.component]"), "{text}");
    // A unit without checks of its own says so rather than leaving a blank.
    assert!(text.contains("Checks"), "{text}");
    assert!(text.contains('\u{2014}'), "{text}");
}

#[test]
fn the_tree_shows_what_holds_for_every_file() {
    let text = report::tree(&analysis(MIXED, MIXED_FILES));

    assert!(text.contains("\u{2713} markdown"), "{text}");
    assert!(text.contains("\u{2013} **/LICENSE"), "{text}");
    assert!(text.contains("\u{2013} *.png"), "{text}");
    assert!(text.contains("? no check"), "{text}");
    assert!(text.contains("\u{d7} rust"), "{text}");
    assert!(
        text.contains("src/"),
        "folders stand there as folders: {text}"
    );
    // The finding hangs under the file it is about.
    assert!(text.contains("uncovered-file"), "{text}");
}

#[test]
fn the_tree_names_a_unit_where_it_begins() {
    let text = report::tree(&analysis(WORKSPACE, WORKSPACE_FILES));

    // What holds everywhere is written once at the repository, not at every
    // line.
    assert_eq!(text.matches("[the repository]").count(), 1, "{text}");
    assert_eq!(
        text.matches("[component docs]").count(),
        1,
        "a unit stands where it begins: {text}"
    );
    // The generated units stand at their file.
    assert!(text.contains("[component a]"), "{text}");
}

#[test]
fn without_a_finding_it_says_so() {
    let text = report::findings(&analysis(WORKSPACE, WORKSPACE_FILES));

    assert_eq!(text, "Findings\n\n  none");
}

#[test]
fn findings_stand_under_each_other() {
    let text = report::findings(&analysis(MIXED, MIXED_FILES));

    assert!(text.contains("error[uncovered-file]"), "{text}");
    assert!(text.contains("error[language-without-check]"), "{text}");
}

#[test]
fn the_line_at_the_end_counts() {
    let many = report::summary(&analysis(MIXED, MIXED_FILES));
    assert_eq!(many, "5 files, 2 gaps, 2 errors, 0 warnings");

    let one = report::summary(&analysis(
        "[repo]\npipeline = \"none\"\n\n[[exclude]]\npath = \"missing.md\"\nreason = \"there is none\"\n",
        &["README.md"],
    ));
    assert_eq!(one, "1 file, 0 gaps, 0 errors, 1 warning");
}

#[test]
fn explain_says_what_holds_for_a_file_and_why() {
    let analysis = analysis(MIXED, MIXED_FILES);

    let file = report::explain(&analysis, &path("src/main.rs")).expect("the file is in the tree");
    assert!(file.contains("Units"), "{file}");
    assert!(file.contains("Coverage"), "{file}");
    assert!(file.contains("Finding"), "{file}");

    let folder = report::explain(&analysis, &path("src")).expect("the folder is in the tree");
    assert!(folder.contains("Holds"), "{folder}");
    assert!(folder.contains("1 entry"), "{folder}");
    assert!(folder.contains("Findings"), "{folder}");

    assert!(report::explain(&analysis, &path("nowhere")).is_none());
}

#[test]
fn explain_counts_several_entries() {
    let analysis = analysis(WORKSPACE, WORKSPACE_FILES);
    let folder = report::explain(&analysis, &path("doc")).expect("the folder is in the tree");

    assert!(folder.contains("2 entries"), "{folder}");
}

#[test]
fn a_name_that_could_forge_a_line_is_escaped() {
    // git allows a newline in a tracked file name. Written out as it stands, it
    // would forge a line of this report — and an escape sequence would set the
    // terminal to something the reader never asked for.
    let analysis = analysis(MIXED, &["README.md", "forged\nline.md"]);
    let text = report::tree(&analysis);

    assert!(text.contains("forged\\nline.md"), "{text}");
    assert_eq!(
        text.lines().count(),
        5,
        "one line per node, and the name does not add one: {text}"
    );

    let explained =
        report::explain(&analysis, &path("forged\nline.md")).expect("the file is in the tree");
    assert!(explained.starts_with("forged\\nline.md"), "{explained}");
}

#[test]
fn the_tree_shows_a_file_the_declaration_excludes_with_its_reason() {
    let declaration = "\
[repo]
pipeline = \"none\"

[[exclude]]
path   = \"docs/draft.md\"
reason = \"a draft that is not published\"
";
    let text = report::tree(&analysis(declaration, &["README.md", "docs/draft.md"]));

    assert!(
        text.lines()
            .any(|line| line.trim_start().starts_with("draft.md")
                && line.ends_with("\u{2013} docs/draft.md: a draft that is not published")),
        "{text}"
    );
}
