//! The plan: which unit runs which check and what it builds, for a matrix to
//! read.
//!
//! Phase 0 decides what holds for a file. A workflow needs the same answer
//! turned around — what to start, and where — and it needs it as data: a matrix
//! is built from JSON, not from a report meant for a reader.
//!
//! Every check runs **once, at the outermost unit it is in force for**. The
//! base set is in force everywhere and so runs at the repository. A check a
//! unit declares covers everything below that unit, so a unit inside it that
//! names the same check again gets no second run over the same files.
//!
//! A build is the other way round: it belongs to **one** unit and is never
//! shared. Its artifact is released under that unit's version, so only a unit
//! that carries a version of its own builds. A unit that generates children
//! leaves the building to them, also when it carries a version beside theirs
//! (`self-and-child-*`): its build would cover the same files a second time.
//!
//! Beside it stands the version of every unit that carries one, as the history
//! resolves it for the commit at hand, with the version writers that copy it
//! into the unit's files before it builds and the targets its artifact is
//! published to. On a pull request that is the version its squash merge would
//! get, with `-pr.<number>` behind it.
//!
//! And it carries for whom the repository is meant, at the commit at hand and
//! at the one before, for what holds only for some repositories.

use crate::finding::UnitName;
use crate::names::{BuildName, CheckName, TargetName, VersionWriterName};
use crate::path::RelativePath;
use crate::resolve::Unit;
use crate::{Analysis, Audience, Central, TagVersion, UnitVersion};
use serde_json::{Value, json};

use crate::versions::of_pull_request;

/// One unit with the checks that are started for it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Planned {
    /// Which unit this is.
    pub name: UnitName,
    /// Where it lives.
    pub path: RelativePath,
    /// The checks started here, in name order. Empty when every check in force
    /// for this unit already runs at a unit containing it.
    pub checks: Vec<CheckName>,
    /// The build started here, if the unit builds anything, carries the
    /// version its artifact is released under and generates no children.
    pub build: Option<BuildName>,
}

/// The version of one unit, and who writes it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Versioned {
    /// The version as the history resolves it.
    pub unit: UnitVersion,
    /// The version writers the unit selects, in the order its pipeline names
    /// them: what copies the version into its files before it builds.
    pub writers: Vec<VersionWriterName>,
    /// The targets the unit publishes to, in the order its pipeline names
    /// them; empty for `publish = false`.
    pub targets: Vec<TargetName>,
}

/// What a run starts.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Plan {
    /// Every unit, repository first, in the order phase 0 resolved them.
    pub units: Vec<Planned>,
    /// The version of every unit that carries one, in the same order.
    pub versions: Vec<Versioned>,
    /// The pull request the plan is built for, if any: every `version` of
    /// [`Plan::to_json`], and the `current` of a unit the pull request
    /// touches, then carries `-pr.<number>` behind it.
    pub pull_request: Option<u64>,
    /// For whom the repository is meant, as the declaration at hand says.
    pub audience: Option<Audience>,
    /// For whom the declaration of the commit before says it is meant: on a
    /// pull request into `main` the tip of `main`.
    pub previous_audience: Option<Audience>,
}

/// Builds the plan from an analysis.
#[must_use]
pub fn plan(analysis: &Analysis, central: &Central) -> Plan {
    let units = &analysis.units;
    let planned = units
        .iter()
        .enumerate()
        .map(|(index, unit)| {
            let mut checks: Vec<CheckName> = unit.pipeline.checks.clone();
            if unit.name == UnitName::Repository {
                checks.extend(central.base_checks().iter().cloned());
            }
            checks.retain(|check| {
                !units
                    .iter()
                    .enumerate()
                    .any(|(other, outer)| runs_first(other, outer, index, unit, check, central))
            });
            checks.sort();
            checks.dedup();
            let builds = unit.carries_version && !unit.versioning.generates_children();
            let build = unit.pipeline.build.clone().filter(|_| builds);
            Planned {
                name: unit.name.clone(),
                path: unit.path.clone(),
                checks,
                build,
            }
        })
        .collect();
    // A unit that carries a version is one phase 0 resolved, so it is always
    // found; a unit generated by another has its writers and targets handed
    // down already.
    let versions = analysis
        .versions
        .iter()
        .map(|version| {
            let unit = units.iter().find(|unit| unit.name == version.name);
            Versioned {
                unit: version.clone(),
                writers: unit
                    .map(|unit| unit.pipeline.version.clone())
                    .unwrap_or_default(),
                targets: unit
                    .map(|unit| unit.pipeline.targets().to_vec())
                    .unwrap_or_default(),
            }
        })
        .collect();
    Plan {
        units: planned,
        versions,
        pull_request: None,
        audience: analysis.audience,
        previous_audience: analysis.previous_audience,
    }
}

/// Whether `outer` already runs this check over everything `unit` holds.
///
/// Two units at the same path contain each other; the one resolved first keeps
/// the check, so that it runs once and not never.
fn runs_first(
    other: usize,
    outer: &Unit,
    index: usize,
    unit: &Unit,
    check: &CheckName,
    central: &Central,
) -> bool {
    if other == index || !outer.path.contains(&unit.path) {
        return false;
    }
    let same_place = outer.path == unit.path;
    if same_place && other > index {
        return false;
    }
    outer.pipeline.checks.contains(check)
        || (outer.name == UnitName::Repository && central.base_checks().contains(check))
}

impl Plan {
    /// The plan as one line of JSON.
    ///
    /// `units` is the plan as it stands, with `build` null for a unit that
    /// builds nothing. `checks` is the checks of it flat, one
    /// entry per check that is started, because a matrix takes a list and
    /// cannot unfold a list inside one.
    ///
    /// `versions` is one entry per unit that carries a version: what the
    /// names of its records start with as `prefix`, its `current` version
    /// (the highest version the history gives any commit of the line up to
    /// the commit at hand, null before the first commit that touches the
    /// unit), the `version` of the commit at hand, null when the commit does
    /// not touch the unit, the `writers` that copy it into the unit's files,
    /// and the `targets` its artifact is published to, empty for
    /// `publish = false`. For a pull request `version` carries `-pr.<number>`
    /// behind it, being the one its squash merge would get, and so does
    /// `current` where the pull request touches the unit: it is that version
    /// then.
    ///
    /// `audience` is for whom the repository is meant, as the declaration at
    /// hand says, and `previous_audience` what the declaration of the commit
    /// before says, null when it names none: on a pull request into `main` the
    /// tip of `main`, so that a change of the value can be shown.
    ///
    /// One line, so that it can be handed on as a step output as it is. Keys
    /// stand in alphabetical order; nothing that reads JSON depends on it.
    #[must_use]
    pub fn to_json(&self) -> String {
        let units: Vec<Value> = self
            .units
            .iter()
            .map(|unit| {
                let mut entry = identity(&unit.name, &unit.path);
                entry["checks"] = unit.checks.iter().map(CheckName::as_str).collect();
                entry["build"] = json!(unit.build.as_ref().map(BuildName::as_str));
                entry
            })
            .collect();
        let checks: Vec<Value> = self
            .units
            .iter()
            .flat_map(|unit| {
                unit.checks.iter().map(move |check| {
                    let mut entry = identity(&unit.name, &unit.path);
                    entry["check"] = json!(check.as_str());
                    entry
                })
            })
            .collect();
        let versions: Vec<Value> = self
            .versions
            .iter()
            .map(|versioned| {
                let Versioned {
                    unit,
                    writers,
                    targets,
                } = versioned;
                let mut entry = identity(&unit.name, &unit.path);
                entry["prefix"] = json!(unit.prefix);
                let written = |version: &TagVersion| {
                    self.pull_request.map_or_else(
                        || version.to_string(),
                        |number| of_pull_request(version, number),
                    )
                };
                // The current version is the commit's own where it has one,
                // and only that one carries the number of a pull request.
                entry["current"] = json!(
                    unit.version
                        .as_ref()
                        .map(written)
                        .or_else(|| { unit.current.as_ref().map(TagVersion::to_string) })
                );
                entry["version"] = json!(unit.version.as_ref().map(written));
                entry["writers"] = writers.iter().map(VersionWriterName::as_str).collect();
                entry["targets"] = targets.iter().map(TargetName::as_str).collect();
                entry
            })
            .collect();
        // Writing a value cannot fail: every key is a string, and nothing here
        // has a serializer of its own that could refuse.
        json!({
            "audience": self.audience.map(Audience::as_str),
            "checks": checks,
            "previous_audience": self.previous_audience.map(Audience::as_str),
            "units": units,
            "versions": versions,
        })
        .to_string()
    }
}

/// The fields that say which unit an entry is about.
///
/// The repository has no name — its tags carry only the prefix `v` — so the
/// kind stands beside it rather than a reserved word a component could also be
/// called.
fn identity(name: &UnitName, path: &RelativePath) -> Value {
    let (kind, name) = match name {
        UnitName::Repository => ("repository", Value::Null),
        UnitName::Component(name) => ("component", json!(name.as_str())),
    };
    json!({ "kind": kind, "name": name, "path": path.to_string() })
}
